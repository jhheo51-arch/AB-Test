from make_shorts import EPISODES, fields

def shot(speaker, text, title, cards, cues=(), dots=()):
    return speaker,text,title,cards,cues,dots

def card(title,value,note):
    return fields(title,value,note)

def pair(first,second):
    return [first,second]

def one(title,value,note):
    return [card(title,value,note)]

