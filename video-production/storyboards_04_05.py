SMALL,LARGE=200,2000
pa,pb=.10,.13
gap=100*(pb-pa)
def interval(n):
    half=1.96*100*math.sqrt((pa*(1-pa)+pb*(1-pb))/n)
    return gap-half,gap+half
def interval_text(n):
    low,high=interval(n)
    return f"{low:+.1f} ~ {high:+.1f}%포인트"
assert round(gap,6)==3 and interval(SMALL)[0]<0<interval(LARGE)[0]

